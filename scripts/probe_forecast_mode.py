"""Probe the RQ2 finding: holding pH, aw and LAB at their origin values predicts as well as
(or better than) the measured future trajectories on unseen sources.

Checks, per organism, on the primary split (folds grouped by source, origin 0):

1. source share: how much of each pH/LAB feature's variance (and of the target, the log
   change from the anchor) lies between sources;
2. gap by source: which held-out sources produce the measured-vs-naive difference;
3. extrapolation: how often held-out feature values fall outside the training sources' range,
   in measured vs naive inputs;
4. training mode: models trained on naive inputs (``run_experiments.py --train-mode naive``)
   compared with models trained on measured inputs, when that run exists.

Writes ``reports/experiments/source_id/probe_forecast_mode.md`` and CSV tables.

Example (from the repository root):
    python scripts/probe_forecast_mode.py
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from cheese_fate import analysis
from cheese_fate.combase import load_exports
from cheese_fate.tasks import build_records, features, make_task

ROOT = Path(__file__).resolve().parents[1]
ORGANISMS = ("Escherichia coli", "Staphylococcus aureus")
PROBED = ("ph_now", "ph_mean", "ph_min_hist", "ph_rebound", "aw_now", "lab_now", "lab_mean",
          "lab_max_hist", "temp_mean", "hours_warm")
MODELS = ("gru", "lstm", "gbt", "residual_gbt")


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def feature_table(records, mode: str) -> pd.DataFrame:
    frames = []
    for record in records:
        task = make_task(record, 0.0, mode=mode)
        if task is None:
            continue
        frame = features(task).assign(
            record_id=record.record_id, source_id=record.source_id,
            change=task.log_counts - task.anchor_log, censored=task.censored)
        frames.append(frame)
    return pd.concat(frames, ignore_index=True)


def markdown(frame: pd.DataFrame, digits: int = 2) -> str:
    def cell(v):
        return f"{v:.{digits}f}" if isinstance(v, (float, np.floating)) else str(v)

    lines = ["| " + " | ".join(map(str, frame.columns)) + " |", "|" + "---|" * len(frame.columns)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--exports", type=Path, default=ROOT / "data/raw/combase_cheese/exports")
    parser.add_argument("--experiments", type=Path, default=ROOT / "reports/experiments")
    args = parser.parse_args()
    export = load_exports(args.exports)
    folder = args.experiments / "source_id"
    lines = ["# Probe: why measured future pH/LAB do not help on unseen sources", "",
             "Generated by `scripts/probe_forecast_mode.py` (folds grouped by source, "
             "origin 0).", ""]
    for organism in ORGANISMS:
        name = slug(organism)
        observations = pd.read_csv(ROOT / f"data/processed/cheese/observations_{name}.csv")
        records, _ = build_records(observations, export)
        run = json.loads((folder / f"{name}_run.json").read_text())
        fold_of = run["assignment"]
        measured = feature_table(records, "measured")
        naive = feature_table(records, "naive")
        lines += [f"## *{organism}*", ""]

        detected = measured[~measured["censored"]]
        share = analysis.between_group_share(detected, ["change", *PROBED])
        share.to_csv(folder / f"probe_{name}_source_share.csv", index=False)
        lines += ["### 1. Variance between sources (measured inputs, detected targets)", "",
                  "`change` is the target (log change from the anchor).", "",
                  markdown(share), ""]

        predictions = pd.read_csv(folder / f"{name}_predictions.csv.gz")
        gaps = []
        for model in MODELS:
            table = analysis.gap_by_group(predictions, model)
            table.to_csv(folder / f"probe_{name}_gap_by_source_{model}.csv", index=False)
            top = table.head(3)
            total = table["difference"].sum()
            gaps.append({
                "model": model, "gap_sse_total": total,
                "sources_worse_measured": int((table["difference"] > 0).sum()),
                "sources": len(table),
                "top3_sources": ", ".join(top["source_id"]),
                "gap_top3": float(top["difference"].sum()),
                "gap_other_sources": float(total - top["difference"].sum()),
            })
        lines += ["### 2. Measured − naive squared-error sum by held-out source", "",
                  "Positive = measured inputs worse. `gap_top3` comes from the three sources where "
                  "measured inputs hurt most; `gap_other_sources` from all the others.", "", markdown(pd.DataFrame(gaps)), ""]

        rows = []
        for fold in sorted(set(fold_of.values())):
            test_ids = {r for r, f in fold_of.items() if f == fold}
            for mode, table in (("measured", measured), ("naive", naive)):
                train = measured[~measured["record_id"].isin(test_ids)]  # models train on measured
                test = table[table["record_id"].isin(test_ids)]
                share_out = analysis.outside_training_range(train, test, PROBED)
                rows.append({"fold": fold, "mode": mode, **share_out.to_dict()})
        outside = pd.DataFrame(rows).groupby("mode")[list(PROBED)].mean().T.reset_index()
        outside = outside.rename(columns={"index": "variable"})
        outside.to_csv(folder / f"probe_{name}_outside_range.csv", index=False)
        lines += ["### 3. Held-out values outside the training 5–95% range (mean over folds)", "",
                  markdown(outside), ""]

        naive_folder = args.experiments / "source_id_naive_train"
        path = naive_folder / f"{name}_predictions.csv.gz"
        if path.exists():
            trained_naive = analysis.summary_table(pd.read_csv(path))
            trained_measured = analysis.summary_table(predictions)
            keep = ["model", "mode", "origin_h", "rmse"]
            both = trained_measured[keep].merge(trained_naive[keep], on=["model", "mode", "origin_h"],
                                                suffixes=("_train_measured", "_train_naive"))
            both = both[both["mode"].isin(["measured", "naive"])]
            both.to_csv(folder / f"probe_{name}_training_mode.csv", index=False)
            pivot = both[both["origin_h"] == 0].drop(columns="origin_h")
            lines += ["### 4. Training mode: trained on measured vs naive inputs (pooled RMSE, origin 0)",
                      "", markdown(pivot), ""]
    (folder / "probe_forecast_mode.md").write_text("\n".join(lines))
    print(f"wrote {folder / 'probe_forecast_mode.md'}")


if __name__ == "__main__":
    main()
