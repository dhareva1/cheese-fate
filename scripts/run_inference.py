"""Source-bootstrap intervals and paired tests for experiment predictions.

For each experiment folder and organism, writes to ``reports/experiments/<name>/``:

- ``<organism>_validation.csv``: RMSE, skill, Bf, Af and ASZ with 95% source-bootstrap
  intervals, per model, mode and origin;
- ``<organism>_comparisons.csv``: paired RMSE differences with Holm-adjusted p-values within
  each family of comparisons (RQ1 hybrid vs components, RQ2 input modes, RQ3 LAB);
- ``inference.md``: the main tables.

Example (from the repository root):
    python scripts/run_inference.py --names source_id food
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from cheese_fate.inference import holm, paired_difference, validation_table

ROOT = Path(__file__).resolve().parents[1]
ORGANISMS = {"escherichia_coli": "Escherichia coli",
             "staphylococcus_aureus": "Staphylococcus aureus"}
ML = ("gbt", "gru", "lstm", "residual_gbt", "node_hybrid")


def comparisons(models: set[str], origins) -> list[tuple[str, tuple]]:
    """(family, comparison) pairs; Holm is applied within each family."""
    out = []
    for origin in origins:
        for a, b in (("residual_gbt", "gbt"), ("residual_gbt", "mechanistic"),
                     ("node_hybrid", "gru"), ("node_hybrid", "mechanistic"),
                     ("gru", "gbt")):
            if {a, b} <= models:
                out.append(("RQ1 model vs model", ((a, "measured"), (b, "measured"), origin)))
        for model in ML:
            if model in models:
                for mode in ("naive", "coupled"):
                    out.append(("RQ2 forecast vs measured", ((model, mode), (model, "measured"), origin)))
        for with_lab in ("gbt", "residual_gbt"):
            if {with_lab, f"{with_lab}_nolab"} <= models:
                for mode in ("measured", "naive", "coupled"):
                    out.append(("RQ3 LAB vs no LAB",
                                ((with_lab, mode), (f"{with_lab}_nolab", mode), origin)))
    return out


def fmt(value, lo, hi, digits=2) -> str:
    return f"{value:.{digits}f} [{lo:.{digits}f}, {hi:.{digits}f}]"


def pval(p) -> str:
    if pd.isna(p):
        return ""
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT / "reports/experiments")
    parser.add_argument("--names", nargs="+", default=["source_id", "food"])
    parser.add_argument("--boot", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    for name in args.names:
        folder = args.root / name
        lines = [f"# Inference ({name})", "",
                 "Generated by `scripts/run_inference.py`. Intervals are 95% percentile "
                 f"intervals from {args.boot} cluster-bootstrap resamples of held-out sources. "
                 "Skill = 1 − RMSE/RMSE(persistence), paired within each resample; `p` is the "
                 "one-sided bootstrap p-value for skill > 0. ASZ = share of observations within "
                 "±0.5 log of the prediction (pass ≥ 0.70; Møller et al., 2013); APZ = share of "
                 "residuals (observed − predicted) within [−1, +0.5] log (Oscar, 2005). Bf/Af are "
                 "bias/accuracy factors on log10 counts.",
                 ""]
        for slug, organism in ORGANISMS.items():
            path = folder / f"{slug}_predictions.csv.gz"
            if not path.exists():
                continue
            predictions = pd.read_csv(path)
            table = validation_table(predictions, n_boot=args.boot, seed=args.seed)
            table.to_csv(folder / f"{slug}_validation.csv", index=False)

            pairs = comparisons(set(predictions["model"]), sorted(predictions["origin_h"].unique()))
            result = paired_difference(predictions, [c for _, c in pairs],
                                       n_boot=args.boot, seed=args.seed)
            result.insert(0, "family", [f for f, _ in pairs][:len(result)])
            result["p_holm"] = result.groupby(["family", "origin_h"])["p_two_sided"].transform(
                lambda p: holm(p.to_numpy()))
            result.to_csv(folder / f"{slug}_comparisons.csv", index=False)

            lines += [f"## *{organism}*", "", "### Validation, origin 0", "",
                      "| model | mode | RMSE | skill | p | sources better | bias (log) | Bf | Af | ASZ | APZ |",
                      "|---|---|---|---|---|---|---|---|---|---|---|"]
            origin0 = table[table["origin_h"] == 0].sort_values(["mode", "rmse"])
            for _, r in origin0.iterrows():
                lines.append(
                    f"| {r.model} | {r['mode']} | {fmt(r.rmse, r.rmse_lo, r.rmse_hi)} | "
                    f"{fmt(r.skill, r.skill_lo, r.skill_hi)} | "
                    f"{pval(r.p_skill)} | "
                    f"{r.sources_better}/{r.n_sources} | {fmt(r.bias, r.bias_lo, r.bias_hi)} | "
                    f"{r.bf:.2f} | {r.af:.2f} | {r.asz:.2f}{' ✓' if r.asz_pass else ''} | {r.apz:.2f} |")
            lines += ["", "### Paired comparisons, origin 0 (RMSE a − b; negative = a better)", "",
                      "| family | a | b | difference | p | p (Holm) |", "|---|---|---|---|---|---|"]
            for _, r in result[result["origin_h"] == 0].iterrows():
                lines.append(f"| {r.family} | {r.a} | {r.b} | "
                             f"{fmt(r.difference, r.difference_lo, r.difference_hi)} | "
                             f"{pval(r.p_two_sided)} | {pval(r.p_holm)} |")
            lines.append("")
            print(f"{name} / {organism}: done", flush=True)
        (folder / "inference.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
